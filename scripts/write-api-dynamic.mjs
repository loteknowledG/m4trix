/**
 * Ensures App Router API routes export a statically analyzable
 * `export const dynamic = "..."` string literal (Next.js requirement).
 *
 * pages / GitHub Actions → force-static (static export)
 * everything else → force-dynamic (dev + Electron desktop)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const apiRoot = path.join(root, 'src', 'app', 'api');

const isPages =
  process.env.M4TRIX_BUILD_TARGET === 'pages' || process.env.GITHUB_ACTIONS === 'true';
const value = isPages ? 'force-static' : 'force-dynamic';

const routeFiles = [
  path.join(apiRoot, '_segment-config.ts'),
  path.join(apiRoot, 'lmstudio', 'health', 'route.ts'),
  path.join(apiRoot, 'models', 'route.ts'),
  path.join(apiRoot, 'img', 'route.ts'),
  path.join(apiRoot, 'google-photos', 'route.ts'),
  path.join(apiRoot, 'app-version', 'route.ts'),
  path.join(apiRoot, 'agent-roles', 'route.ts'),
  path.join(apiRoot, 'agents', 'route.ts'),
  path.join(apiRoot, 'tts', 'route.ts'),
  path.join(apiRoot, 'samus-memory', 'route.ts'),
];

const DYNAMIC_LINE = `export const dynamic = "${value}";`;
const DYNAMIC_RE =
  /export\s+\{\s*dynamic\s*\}\s+from\s+['"][^'"]+['"]\s*;?|export\s+const\s+dynamic\s*=\s*[^;\n]+;?/g;

for (const file of routeFiles) {
  if (!fs.existsSync(file)) continue;
  const original = fs.readFileSync(file, 'utf8');
  let next = original;

  if (file.endsWith(`${path.sep}_segment-config.ts`)) {
    next = `// Generated by scripts/write-api-dynamic.mjs — do not edit by hand.\n${DYNAMIC_LINE}\n`;
  } else if (DYNAMIC_RE.test(original)) {
    DYNAMIC_RE.lastIndex = 0;
    next = original.replace(DYNAMIC_RE, DYNAMIC_LINE);
  } else if (/export\s+const\s+runtime\s*=/.test(original)) {
    next = original.replace(
      /(export\s+const\s+runtime\s*=\s*[^;]+;)/,
      `$1\n${DYNAMIC_LINE}`,
    );
  } else {
    next = `${DYNAMIC_LINE}\n${original}`;
  }

  if (next !== original) {
    fs.writeFileSync(file, next, 'utf8');
    console.log(`[write-api-dynamic] updated ${path.relative(root, file)} → ${value}`);
  } else {
    console.log(`[write-api-dynamic] ok ${path.relative(root, file)} → ${value}`);
  }
}
